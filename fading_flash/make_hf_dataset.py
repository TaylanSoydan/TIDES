def generate(n, seed, dt_range=TRAIN_DT_RANGE, chunk=1000):
    """n sequences from task.sample_batch with a fixed seed -> dict of numpy arrays."""
    np.random.seed(seed)
    torch.manual_seed(seed)
    parts = {'flash': [], 'rate': [], 'dt': [], 'glow': []}
    for start in range(0, n, chunk):
        x, dt, y = sample_batch(min(chunk, n - start), dt_range=dt_range)
        parts['flash'].append(x[..., 0].numpy().astype(np.float32))
        parts['rate'].append(x[..., 1:].argmax(-1).numpy().astype(np.int8))
        parts['dt'].append(dt.numpy().astype(np.float32))
        parts['glow'].append(y[..., 0].numpy().astype(np.float32))
    return {k: np.concatenate(v) for k, v in parts.items()}


def write_parquet(cols, path):
    import pyarrow as pa
    import pyarrow.parquet as pq
    table = pa.table({
        'flash': pa.FixedSizeListArray.from_arrays(pa.array(cols['flash'].ravel()), L),
        'rate': pa.FixedSizeListArray.from_arrays(pa.array(cols['rate'].ravel()), L),
        'dt': pa.array(cols['dt']),
        'glow': pa.FixedSizeListArray.from_arrays(pa.array(cols['glow'].ravel()), L),
    })
    pq.write_table(table, path)
    print(f'  {path}: {table.num_rows:,} rows, {os.path.getsize(path) / 1e6:.1f} MB')


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--out_dir', default='data/fading_flash_hf')
    p.add_argument('--n_train', type=int, default=100_000)
    p.add_argument('--n_val', type=int, default=5_000)
    p.add_argument('--n_test', type=int, default=2_000, help='sequences per test Δ')
    p.add_argument('--hub_id', default='<user>/fading-flash',
                   help='repo id used in the dataset card example')
    args = p.parse_args()

    os.makedirs(os.path.join(args.out_dir, 'data'), exist_ok=True)
    splits = {
        'train': generate(args.n_train, SPLIT_SEEDS['train']),
        'validation': generate(args.n_val, SPLIT_SEEDS['validation']),
    }
    test = [generate(args.n_test, SPLIT_SEEDS['test'] * 1000 + i, dt_range=(float(d), float(d)))
            for i, d in enumerate(DT_GRID)]
    splits['test'] = {k: np.concatenate([t[k] for t in test]) for k in test[0]}

    print(f'Writing {args.out_dir}/')
    for name, cols in splits.items():
        write_parquet(cols, os.path.join(args.out_dir, 'data', f'{name}.parquet'))

    rates = ', '.join(f'{r:g}' for r in RATE_LEVELS.tolist())
    card = CARD.format(
        L=L, rates=rates, lo=TRAIN_DT_RANGE[0], hi=TRAIN_DT_RANGE[1],
        grid=', '.join(f'{d:g}' for d in DT_GRID), n_train=args.n_train, n_val=args.n_val,
        n_test=args.n_test, n_test_total=args.n_test * len(DT_GRID), n_grid=len(DT_GRID),
        hub_id=args.hub_id, s_tr=SPLIT_SEEDS['train'], s_va=SPLIT_SEEDS['validation'],
        s_te=f"{SPLIT_SEEDS['test']}000 + i for the i-th Δ")
    with open(os.path.join(args.out_dir, 'README.md'), 'w') as f:
        f.write(card)
    print(f'  {args.out_dir}/README.md (dataset card)')
    assert N_RATES == 3


if __name__ == '__main__':
    main()
